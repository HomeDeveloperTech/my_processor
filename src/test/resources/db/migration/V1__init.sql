CREATE TABLE CLIENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENT_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    FULL_NAME VARCHAR2(150) NOT NULL,
    BIRTH_DATE DATE NOT NULL,
    EMAIL VARCHAR2(150),
    PHONE_NUMBER VARCHAR2(20),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE FICO_REQUESTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID NUMBER NOT NULL,
    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    CHANNEL VARCHAR2(50),
    CONSTRAINT FK_FICO_REQUESTS_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENTS (ID)
);

CREATE TABLE FICO_SCORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FICO_REQUEST_ID NUMBER NOT NULL,
    SCORE NUMBER(3) NOT NULL,
    CALCULATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DETAILS CLOB,
    CONSTRAINT FK_FICO_SCORES_REQUEST FOREIGN KEY (FICO_REQUEST_ID) REFERENCES FICO_REQUESTS (ID)
);

CREATE INDEX IDX_FICO_REQUESTS_CLIENT ON FICO_REQUESTS (CLIENT_ID);
CREATE INDEX IDX_FICO_SCORES_REQUEST ON FICO_SCORES (FICO_REQUEST_ID);
